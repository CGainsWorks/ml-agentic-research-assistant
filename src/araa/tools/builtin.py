"""The tool inventory.

Four tools, all read-only. See docs/tool_inventory.md for the rendered version
of this list (generated by `python -m araa.tools.builtin --inventory`).

    search_corpus     hybrid retrieval over the paper corpus
    lookup_document   metadata and abstract for one document
    query_table       aggregate over the corpus metadata table
    calculate         arithmetic, evaluated by an AST walker, not by eval()

`query_table` and `calculate` exist because a retrieval-only agent gets
arithmetic questions wrong in a specific and recognisable way: it reads a
handful of retrieved rows, counts those, and reports the count as if it were the
whole corpus. Counting is not retrieval, and the fix is a tool, not a longer
prompt.
"""

from __future__ import annotations

import ast
import json
import operator
from typing import Any

from araa.config import Settings
from araa.ingestion.tabular import TableStore
from araa.retrieval.hybrid import HybridRetriever
from araa.tools.base import Tool, ToolParam, ToolRegistry, ToolResult


class SearchCorpusTool(Tool):
    name = "search_corpus"
    description = (
        "Search the paper corpus. Returns the most relevant passages with their provenance."
    )
    params = [
        ToolParam("query", "What to search for. Use the corpus's own terminology.", required=True),
        ToolParam("top_k", "How many passages to return.", default=5),
    ]

    def __init__(self, retriever: HybridRetriever) -> None:
        self.retriever = retriever

    def run(self, args: dict[str, str]) -> ToolResult:
        try:
            top_k = max(1, min(10, int(args.get("top_k", 5))))
        except ValueError:
            top_k = 5
        trace = self.retriever.retrieve(args["query"], top_k=top_k)
        if not trace.results:
            return ToolResult(self.name, True, "No passages matched that query.", data=[])

        lines = []
        for r in trace.results:
            meta = r.chunk.metadata
            head = f"{meta.get('title', r.chunk.doc_id)}"
            if meta.get("section"):
                head += f" | {meta['section']}"
            lines.append(f"[{r.chunk.chunk_id}] {head}\n{r.chunk.text[:700]}")
        return ToolResult(
            self.name,
            True,
            "\n\n".join(lines),
            data=[r.to_dict(include_text=False) for r in trace.results],
        )


class LookupDocumentTool(Tool):
    name = "lookup_document"
    description = (
        "Fetch title, authors, categories, licence and abstract for one document by its arXiv id."
    )
    params = [ToolParam("doc_id", "The arXiv id, e.g. 2401.12345.", required=True)]

    def __init__(self, retriever: HybridRetriever) -> None:
        self.retriever = retriever

    def run(self, args: dict[str, str]) -> ToolResult:
        doc_id = args["doc_id"].strip()
        chunks = [c for c in self.retriever.chunks.all() if c.doc_id == doc_id]
        if not chunks:
            return ToolResult(self.name, False, "", error=f"no document {doc_id!r} in the corpus")
        meta = chunks[0].metadata
        abstract = next((c.text for c in chunks if c.metadata.get("block_type") == "abstract"), "")
        body = (
            f"Title: {meta.get('title')}\n"
            f"Authors: {meta.get('authors')}\n"
            f"Categories: {meta.get('categories')}\n"
            f"Licence: {meta.get('licence')}\n"
            f"URL: {meta.get('url')}\n"
            f"Chunks indexed: {len(chunks)}\n\n"
            f"Abstract: {abstract[:1200]}"
        )
        return ToolResult(self.name, True, body, data=meta)


class QueryTableTool(Tool):
    name = "query_table"
    description = (
        "Compute over the corpus metadata table. Use this for counting, grouping and "
        "filtering questions - retrieval cannot count."
    )
    params = [
        ToolParam("table", "Table name.", default="corpus_metadata"),
        ToolParam("op", "One of: schema, value_counts, aggregate, filter.", required=True),
        ToolParam("column", "Column to count, group by, or filter on."),
        ToolParam("contains", "Substring to filter for (op=filter)."),
        ToolParam("limit", "Maximum rows returned.", default=20),
    ]

    def __init__(self, store: TableStore) -> None:
        self.store = store

    def run(self, args: dict[str, str]) -> ToolResult:
        table = args.get("table", "corpus_metadata")
        op = args["op"].lower()
        try:
            limit = max(1, min(100, int(args.get("limit", 20))))
        except ValueError:
            limit = 20

        if op == "schema":
            return ToolResult(self.name, True, self.store.describe(), data=self.store.schema(table))
        if op == "value_counts":
            rows = self.store.value_counts(table, args["column"], top=limit)
        elif op == "aggregate":
            rows = self.store.aggregate(table, args["column"])
        elif op == "filter":
            rows = self.store.filter_rows(
                table, args["column"], args.get("contains", ""), limit=limit
            )
        else:
            return ToolResult(
                self.name,
                False,
                "",
                error=f"unknown op {op!r}; use schema|value_counts|aggregate|filter",
            )

        pretty = json.dumps(rows, indent=2, default=str)[:2000]
        return ToolResult(self.name, True, f"{len(rows)} rows from {table}:\n{pretty}", data=rows)


_BIN_OPS: dict[type, Any] = {
    ast.Add: operator.add,
    ast.Sub: operator.sub,
    ast.Mult: operator.mul,
    ast.Div: operator.truediv,
    ast.FloorDiv: operator.floordiv,
    ast.Mod: operator.mod,
    ast.Pow: operator.pow,
}
_UNARY_OPS: dict[type, Any] = {ast.UAdd: operator.pos, ast.USub: operator.neg}


def safe_eval(expr: str) -> float:
    """Arithmetic only, via an AST walk.

    Not `eval` with a restricted namespace — that has been escaped too many
    times to be worth defending, and the input here can originate in a document
    an attacker wrote.
    """
    if len(expr) > 200:
        raise ValueError("expression too long")

    def _walk(node: ast.AST) -> float:
        if isinstance(node, ast.Expression):
            return _walk(node.body)
        if isinstance(node, ast.Constant):
            if isinstance(node.value, int | float) and not isinstance(node.value, bool):
                return float(node.value)
            raise ValueError(f"unsupported constant: {node.value!r}")
        if isinstance(node, ast.BinOp):
            op = _BIN_OPS.get(type(node.op))
            if op is None:
                raise ValueError(f"unsupported operator: {type(node.op).__name__}")
            left, right = _walk(node.left), _walk(node.right)
            if isinstance(node.op, ast.Pow) and (abs(right) > 64 or abs(left) > 1e6):
                raise ValueError("exponent out of range")
            return op(left, right)
        if isinstance(node, ast.UnaryOp):
            op = _UNARY_OPS.get(type(node.op))
            if op is None:
                raise ValueError(f"unsupported unary operator: {type(node.op).__name__}")
            return op(_walk(node.operand))
        raise ValueError(f"unsupported expression element: {type(node).__name__}")

    return _walk(ast.parse(expr.strip(), mode="eval"))


class CalculateTool(Tool):
    name = "calculate"
    description = "Evaluate an arithmetic expression, e.g. (88.5 - 84.2) / 84.2 * 100."
    params = [
        ToolParam("expression", "Arithmetic only: + - * / // % ** and parentheses.", required=True)
    ]

    def run(self, args: dict[str, str]) -> ToolResult:
        expr = args["expression"]
        try:
            value = safe_eval(expr)
        except (SyntaxError, ValueError, ZeroDivisionError, OverflowError) as exc:
            return ToolResult(self.name, False, "", error=f"{type(exc).__name__}: {exc}")
        return ToolResult(self.name, True, f"{expr} = {value:.6g}", data=value)


def build_registry(
    settings: Settings, retriever: HybridRetriever, table_store: TableStore | None = None
) -> ToolRegistry:
    registry = ToolRegistry()
    registry.register(SearchCorpusTool(retriever))
    registry.register(LookupDocumentTool(retriever))

    store = table_store or TableStore()
    metadata_csv = settings.corpus_dir / "metadata.csv"
    if metadata_csv.exists():
        try:
            store.register_file("corpus_metadata", metadata_csv)
            registry.register(QueryTableTool(store))
        except Exception:  # noqa: BLE001 - an unreadable CSV should not remove every tool
            pass

    registry.register(CalculateTool())
    return registry


def main() -> int:  # pragma: no cover - documentation helper
    import argparse

    from araa.config import get_settings

    ap = argparse.ArgumentParser()
    ap.add_argument("--inventory", action="store_true", help="print the tool inventory as markdown")
    ap.parse_args()

    s = get_settings()
    registry = build_registry(s, HybridRetriever(s))
    print("# Tool inventory\n")
    print("All tools are read-only. Nothing here writes, sends, or executes.\n")
    for tool in registry.tools.values():
        print(f"## `{tool.name}`\n")
        print(f"{tool.description}\n")
        if tool.params:
            print("| Parameter | Required | Default | Description |")
            print("| --- | --- | --- | --- |")
            for p in tool.params:
                print(
                    f"| `{p.name}` | {'yes' if p.required else 'no'} | `{p.default}` | {p.description} |"
                )
            print()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
