"""Build docs/results.json from the eval artefacts and render docs/results.md.

This is the mechanism behind "every number quoted in the README is reproducible
from a script in this repo". Numbers are never typed in by hand:

1. each eval writes a JSON artefact into `data/runs/` (gitignored: it carries
   per-question detail and is regenerated by `make eval`);
2. `--from-runs` condenses those artefacts into `docs/results.json`, which is
   committed, so every quoted number has an artefact anyone can read;
3. the default mode renders `docs/results.md` from `docs/results.json` alone;
4. `--check` renders in memory and fails if `docs/results.md` differs, which CI
   runs on every push. The README's quoted figures are checked against
   `docs/results.json` by `tests/test_results_doc.py`.

If an eval has not been run, the corresponding section says so rather than
showing a stale figure.

Run:
    python -m evals.report --from-runs   # data/runs/ -> results.json -> results.md
    python -m evals.report               # results.json -> results.md
    python -m evals.report --check       # CI: results.md must match results.json
"""

from __future__ import annotations

import argparse
import difflib
import hashlib
import json
import re
import sys
from pathlib import Path

from evals.harness import fmt_pct

DOCS = Path(__file__).resolve().parents[1] / "docs"
SUMMARY_PATH = DOCS / "results.json"
REPORT_PATH = DOCS / "results.md"

SECTIONS = ("retrieval", "chunking", "groundedness", "adversarial", "costs")
SCHEMA_VERSION = 1

MISSING = "_Not run yet. Produce it with `{cmd}`._"
NA = "n/a"


def _ci(d: dict) -> str:
    if not isinstance(d, dict) or "ci95" not in d:
        return ""
    lo, hi = d["ci95"]
    return f" (95% CI {fmt_pct(lo)} to {fmt_pct(hi)}, n={d['n']})"


def _rate_cell(d: dict) -> str:
    if not isinstance(d, dict):
        return NA
    # An empty denominator is not a rate of zero. Rendering it as "0.0%" is how
    # an unmeasured run gets read as a measured failure, which happened here
    # before the eval learned to distinguish the two.
    if not d.get("n"):
        return "**not measured**"
    return f"{fmt_pct(d.get('rate', 0))}{_ci(d)}"


# ------------------------------------------------------------------ summary
def _drop_paths(config: dict) -> dict:
    """Settings that are filesystem locations say where a run happened, not
    what it measured, and must never put a local path into a committed file."""
    return {k: v for k, v in (config or {}).items() if not k.endswith(("_dir", "_path"))}


def _relabel_pricing(metrics: dict, transformations: list[str]) -> dict:
    """Label projection price points by tier, matched on their rates.

    Older cost artefacts keyed the projection by a vendor model identifier.
    The current eval keys it by tier (`araa.config.PRICING_USD_PER_MTOK`). A
    key is renamed only when its (input, output) rates match a tier exactly,
    so a relabel can never change a number.
    """
    from araa.config import PRICING_USD_PER_MTOK

    by_rates = {tuple(v): k for k, v in PRICING_USD_PER_MTOK.items()}
    pricing = metrics.get("pricing_used_for_projection") or {}
    rename = {}
    for key, rates in pricing.items():
        label = by_rates.get(tuple(rates))
        if label and label != key:
            rename[key] = label
    if not rename:
        return metrics

    def swap(d: dict) -> dict:
        return {rename.get(k, k): v for k, v in d.items()}

    out = json.loads(json.dumps(metrics))
    out["pricing_used_for_projection"] = swap(pricing)
    for mode in out.get("by_mode", {}).values():
        for field in ("projected_cost_usd_per_query", "projected_cost_usd_per_1000_queries"):
            if field in mode:
                mode[field] = swap(mode[field])
    transformations.append(
        "costs: projection price points keyed by a model identifier were relabelled by "
        "tier, matched on identical USD per Mtok rates; no number changed"
    )
    return out


def _current_notes(name: str, notes: list[str], transformations: list[str]) -> list[str]:
    """Notes are prose written by the eval at run time. Two of them carry advice
    whose wording has since changed; they are re-rendered from the current
    code so the report never recommends a flag or label that no longer exists."""
    out = list(notes)
    if name == "groundedness":
        from evals.groundedness.run_groundedness import SELF_JUDGING_PREFIX, self_judging_warning

        for i, note in enumerate(out):
            match = re.match(re.escape(SELF_JUDGING_PREFIX) + r"(.+?)\) is the same model", note)
            if match and note != (fresh := self_judging_warning(match.group(1))):
                out[i] = fresh
                transformations.append(
                    "groundedness: the self-judging warning was re-rendered with the "
                    "current --judge-backend advice"
                )
    if name == "costs":
        from evals.costs.run_cost_report import TIER_LABEL_NOTE

        if TIER_LABEL_NOTE not in out:
            out.append(TIER_LABEL_NOTE)
    return out


def summarise(artefacts: dict[str, dict | None], digests: dict[str, str]) -> dict:
    """The compact, committed form of the eval artefacts.

    Keeps exactly what the report renders, plus enough provenance (config,
    timestamps, a SHA-256 of each source artefact) to say which run a number
    came from. Per-question detail stays in `data/runs/`.
    """
    transformations: list[str] = []
    sections: dict[str, dict | None] = {}
    for name in SECTIONS:
        a = artefacts.get(name)
        if not a:
            sections[name] = None
            continue
        metrics = a["metrics"]
        if name == "retrieval":
            metrics = {
                set_name: {
                    "questions": res["questions"],
                    "lift": res["lift"],
                    "configs": {c: {"metrics": v["metrics"]} for c, v in res["configs"].items()},
                }
                for set_name, res in metrics.items()
            }
        if name == "costs":
            metrics = _relabel_pricing(metrics, transformations)
        sections[name] = {
            "metrics": metrics,
            "notes": _current_notes(name, a.get("notes", []), transformations),
            "provenance": {
                "artefact": f"data/runs/eval-{name}.json",
                "sha256": digests.get(name, ""),
                "finished_at": a.get("finished_at", ""),
                "harness_version": a.get("harness_version", ""),
                "config": _drop_paths(a.get("config", {})),
            },
        }

    env = next((a["environment"] for a in artefacts.values() if a), {})
    index = dict(env.get("index", {}))
    if "config" in index:
        index["config"] = _drop_paths(index["config"])
    finished = sorted(a.get("finished_at", "") for a in artefacts.values() if a)
    return {
        "schema_version": SCHEMA_VERSION,
        "runs_finished_at": finished[-1] if finished else None,
        "environment": {k: env.get(k) for k in ("python", "platform") if k in env},
        "corpus": env.get("corpus", {}),
        "index": index,
        "transformations": sorted(set(transformations)),
        "sections": sections,
    }


def load_runs() -> tuple[dict[str, dict | None], dict[str, str]]:
    from araa.config import get_settings

    runs_dir = get_settings().runs_dir
    artefacts: dict[str, dict | None] = {}
    digests: dict[str, str] = {}
    for name in SECTIONS:
        path = runs_dir / f"eval-{name}.json"
        if not path.exists():
            artefacts[name] = None
            continue
        raw = path.read_bytes()
        artefacts[name] = json.loads(raw.decode("utf-8"))
        digests[name] = hashlib.sha256(raw).hexdigest()
    return artefacts, digests


def dump_summary(summary: dict) -> str:
    # Key order is preserved, not sorted: the report renders modes and
    # configurations in the order the eval wrote them.
    return json.dumps(summary, indent=2, ensure_ascii=False) + "\n"


